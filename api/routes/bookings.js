const express = require("express");
const pool = require("../db");

const router = express.Router();


// Book an appointment using the PostgreSQL stored procedure
router.post("/", async (req, res) => {
    const client = await pool.connect();

    try {
        const {
            patient_id,
            clinic_id,
            copay_amount
        } = req.body;

        // Basic validation
        if (!patient_id || !clinic_id || copay_amount === undefined) {
            return res.status(400).json({
                error: "patient_id, clinic_id and copay_amount are required"
            });
        }

        if (Number(copay_amount) < 0) {
            return res.status(400).json({
                error: "Copay amount cannot be negative"
            });
        }

        await client.query("BEGIN");

        // Get HSA balance BEFORE booking
        const beforeResult = await client.query(
            `SELECT hsa_balance
             FROM patients
             WHERE id = $1
             FOR UPDATE`,
            [patient_id]
        );

        if (beforeResult.rows.length === 0) {
            await client.query("ROLLBACK");

            return res.status(404).json({
                error: "Patient not found"
            });
        }

        const hsaBefore = beforeResult.rows[0].hsa_balance;

        // Call the existing PostgreSQL stored procedure
        await client.query(
            `CALL book_appointment($1, $2, $3)`,
            [
                patient_id,
                clinic_id,
                copay_amount
            ]
        );

        // Get HSA balance AFTER booking
        const afterResult = await client.query(
            `SELECT hsa_balance
             FROM patients
             WHERE id = $1`,
            [patient_id]
        );

        const hsaAfter = afterResult.rows[0].hsa_balance;

        // Get the newly created appointment
        const appointmentResult = await client.query(
            `SELECT
                a.id,
                a.patient_id,
                p.name AS patient_name,
                a.clinic_id,
                c.name AS clinic_name,
                a.copay_amount,
                a.status,
                a.created_at
             FROM appointments a
             JOIN patients p
                ON a.patient_id = p.id
             JOIN clinics c
                ON a.clinic_id = c.id
             WHERE a.patient_id = $1
             ORDER BY a.created_at DESC
             LIMIT 1`,
            [patient_id]
        );

        // Get the audit log generated by the HSA trigger
        const auditResult = await client.query(
            `SELECT
                id,
                patient_id,
                amount_changed,
                action_type,
                balance_after,
                timestamp
             FROM wallet_audit_logs
             WHERE patient_id = $1
             ORDER BY timestamp DESC
             LIMIT 1`,
            [patient_id]
        );

        await client.query("COMMIT");

        res.status(201).json({
            message: "Appointment booked successfully",

            hsa: {
                before: hsaBefore,
                after: hsaAfter,
                amount_charged: copay_amount
            },

            appointment: appointmentResult.rows[0],

            audit_log: auditResult.rows[0]
        });

    } catch (error) {

        await client.query("ROLLBACK");

        console.error(error);

        // Insufficient HSA / other stored procedure errors
        if (error.code === "P0001") {
            return res.status(400).json({
                error: error.message
            });
        }

        // Partial unique index:
        // patient already has WAITING / IN_CONSULTATION appointment
        if (error.code === "23505") {
            return res.status(409).json({
                error: "Patient already has an active appointment"
            });
        }

        res.status(500).json({
            error: "Failed to book appointment"
        });
    } finally {
        client.release();
    }
});


module.exports = router;